"""Generate the C++ dispatch rows from the Python W4A16 catalog."""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from moe_utils.w4a16_modes import BSTAT_FALLBACK_TILE, PREFILL_PIPELINES, W4A16_SPECS, w4a16_unfused_mode

TABLE = ROOT / 'csrc_for_aiter/936_938/moe_w4a16_mode_table.h'
PIPELINES = ROOT / 'csrc_for_aiter/936_938/moe_w4a16_prefill_pipeline.h'


def _launch(spec, p, tile=None):
    def epilogue():
        name = 'DownWeighted' if spec.stage == 2 else 'UpSilu' if p['silu'] else 'Up'
        return 'W4A16Epilogue::' + name

    if spec.implementation == 'legacy_decode':
        fn = 'launch_w4a16_legacy'
        args = [spec.stage, spec.bm, *(p[k] for k in ('bn', 'bk', 'wm', 'wn', 'wk', 'st')), 'T']
    elif spec.implementation == 'decode':
        fn = 'launch_moe_w4a16_decode'
        args = [spec.bm, p['wn'] * p['nn'] * 16, p['pd'], epilogue(), 'T', 'GS']
    elif spec.implementation == 'prefill':
        fn = 'launch_moe_w4a16_prefill'
        args = [spec.bm, tile.bn, tile.nloop, 'W4A16Pipeline::' + tile.pipeline, epilogue(), 'T', 'GS']
    else:
        assert spec.implementation == 'bstat'
        fn = 'launch_w4a16_bstat_or_streamed'
        args = [spec.bm, p['warps'] * p['nn'] * 16, 'T', 'GS']
    return fn + '<' + ', '.join(str(x).lower() if isinstance(x, bool) else str(x) for x in args) + '>'


def _preamble():
    return ['// Copyright (c) 2026 Hygon Information Technology Co., Ltd.',
            '// SPDX-License-Identifier: MIT',
            '// Generated by tune/gen_w4a16_mode_table.py; edit moe_utils/w4a16_modes.py.',
            '#pragma once', '']


def render_pipelines():
    lines = _preamble() + [
        'enum class W4A16Pipeline {',
        *(f'    {name},' for name in PREFILL_PIPELINES),
        '};',
        'enum class W4A16Epilogue { Up, UpSilu, DownWeighted };', '',
        'namespace w4a16_prefill {', '',
        f'constexpr int BstatFallbackBN = {BSTAT_FALLBACK_TILE.bn};',
        f'constexpr int BstatFallbackNLoop = {BSTAT_FALLBACK_TILE.nloop};',
        f'constexpr auto BstatFallbackPipeline = W4A16Pipeline::{BSTAT_FALLBACK_TILE.pipeline};', '',
        'template <int BM, W4A16Pipeline Pipeline>',
        'struct PipelineTraits;', '',
    ]
    for name, p in PREFILL_PIPELINES.items():
        wpe = p.wpe if p.small_bm_wpe is None else f'BM == 32 ? {p.small_bm_wpe} : {p.wpe}'
        lines += [
            'template <int BM>',
            f'struct PipelineTraits<BM, W4A16Pipeline::{name}> {{',
            f'    static constexpr int NN = {4 if p.wide_n else 2};',
            f'    static constexpr int ST = {p.st}, WPE = {wpe}, SCM = {p.scm}, AH = {p.ah}, OPT = {p.opt};',
            f'    static constexpr bool PREFETCH_A = {str(p.prefetch_a).lower()};',
            '};', '',
        ]
    lines += [
        'template <int BM, int BN, W4A16Pipeline Pipeline>',
        'struct Tile : PipelineTraits<BM, Pipeline> {',
        '    using Schedule = PipelineTraits<BM, Pipeline>;',
        '    static_assert(BM > 0 && BM % 16 == 0 && BN > 0 && BN % (16 * Schedule::NN) == 0,',
        '                  "invalid W4A16 prefill tile");',
        '    static constexpr int WARPS = BN / (16 * Schedule::NN);',
        '    static constexpr int MinWaves = Schedule::WPE > 0 ? Schedule::WPE',
        '                                                       : (Schedule::ST == 1 ? 2 * WARPS / 4 : 1);',
        '};', '',
        '} // namespace w4a16_prefill', '',
    ]
    return '\n'.join(lines)


def render():
    lines = _preamble()
    for stage in (1, 2):
        for family, name in ((0, 'decode'), (1, 'prefill')):
            lines += ['template <typename T, int GS>', f'constexpr W4A16Mode<T> w4a16_gemm{stage}_{name}[] = {{']
            last_bm = 0
            for mode_id, spec in sorted(W4A16_SPECS.items()):
                if (spec.stage, spec.family) != (stage, family):
                    continue
                if spec.bm != last_bm:
                    lines.append(f'    // BM = {spec.bm}')
                    last_bm = spec.bm
                prefix = f'{stage}, 1, {family}, {spec.bm}, '
                twin_id = w4a16_unfused_mode(mode_id)
                twin = f'encode_moe_channel_mode({prefix}{twin_id % 1000})' if twin_id else '0'
                lines.append(f'    {{encode_moe_channel_mode({prefix}{spec.profile}), {twin},')
                launch = _launch(spec, spec.template, spec.prefill_tile)
                if spec.fp16_overrides:
                    fp16 = _launch(spec, dict(spec.template, **spec.fp16_overrides), spec.fp16_prefill_tile)
                    lines += [f'     [] {{ if constexpr (std::is_same_v<T, half>) return &{fp16};',
                              f'          else return &{launch}; }}()}},']
                elif spec.implementation == 'legacy_decode':
                    lines.append(f'     GS == 32 ? &{launch} : nullptr}},')
                else:
                    lines.append(f'     &{launch}}},')
            lines += ['};', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in ((TABLE, render()), (PIPELINES, render_pipelines())):
        if args.check:
            if not path.exists() or path.read_text() != expected:
                parser.exit(1, f'{path.name} is out of date; rerun {Path(__file__).name}\n')
        else:
            path.write_text(expected)


if __name__ == '__main__':
    main()
